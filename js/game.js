  function buildMapPaths() {
    if (!dom.mapBasePath || !dom.mapPassedPath) return;

    // 단계별 좌표를 SVG 800x450 좌표계로 변환 (800 * x/100, 450 * y/100)
    const pts = modeData.stages.map(s => ({
      x: (800 * s.coord.x) / 100,
      y: (450 * s.coord.y) / 100
    }));

    if (pts.length < 2) return;

    let d = `M ${pts[0].x} ${pts[0].y}`;
    for (let i = 1; i < pts.length; i++) {
      const prev = pts[i - 1];
      const curr = pts[i];
      const midX = (prev.x + curr.x) / 2;
      const midY = (prev.y + curr.y) / 2;
      d += ` Q ${prev.x} ${curr.y} ${curr.x} ${curr.y}`;
    }

    dom.mapBasePath.setAttribute('d', d);
    dom.mapPassedPath.setAttribute('d', d);
    dom.mapPassedPath.style.strokeDashoffset = 1000;
  }

  function buildCheckpoints() {
    if (!dom.mapPoints) return;
    dom.mapPoints.innerHTML = '';

    modeData.stages.forEach((stage, idx) => {
      const cp = document.createElement('div');
      cp.className = `map-checkpoint ${idx === 0 ? 'current' : ''}`;
      cp.id = `checkpoint-${idx}`;
      cp.style.left = stage.coord.x + '%';
      cp.style.top = stage.coord.y + '%';
      cp.innerHTML = `
        <span class="checkpoint-pin"></span>
        <span class="checkpoint-label">${stage.step}. ${stage.name || stage.title.split(' ')[0]}</span>
      `;
      dom.mapPoints.appendChild(cp);
    });
  }

  function updateMapPositions(stageIdx) {
    const stage = modeData.stages[stageIdx];
    if (!stage) return;

    // 움직이는 토큰 글라이딩 이동
    if (dom.mapToken) {
      dom.mapToken.style.left = stage.coord.x + '%';
      dom.mapToken.style.top = stage.coord.y + '%';
    }

    // 체크포인트 상태 갱신
    modeData.stages.forEach((_, idx) => {
      const cp = $(`checkpoint-${idx}`);
      if (!cp) return;
      cp.className = 'map-checkpoint';
      if (idx < stageIdx) cp.classList.add('passed');
      else if (idx === stageIdx) cp.classList.add('current');
    });

    // 지나온 SVG 패스 채우기 애니메이션
    if (dom.mapPassedPath) {
      const totalLen = 1000;
      const progress = stageIdx / (modeData.stages.length - 1);
      const offset = totalLen * (1 - progress);
      dom.mapPassedPath.style.strokeDashoffset = offset;
    }
  }

