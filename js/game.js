  // 6. HUD 상태값 갱신
  // ============================================================
  function updateHUD(deltas) {
    modeData.resources.forEach(res => {
      const val = currentResources[res.key];
      const valEl = $(`val-${res.key}`);
      const barEl = $(`bar-${res.key}`);
      const cardEl = $(`stat-card-${res.key}`);

      if (valEl) valEl.textContent = Math.max(0, val);
      if (barEl) {
        const pct = Math.min(100, Math.max(0, (val / res.max) * 100));
        barEl.style.width = pct + '%';
      }

      if (deltas && deltas[res.key] !== undefined && deltas[res.key] !== 0 && cardEl) {
        const cls = deltas[res.key] > 0 ? 'flash-up' : 'flash-down';
        cardEl.classList.remove('flash-up', 'flash-down');
        void cardEl.offsetWidth;
        cardEl.classList.add(cls);
        setTimeout(() => cardEl.classList.remove(cls), 650);
      }
    });
  }

