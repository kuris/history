  // 10. 결과 공유하기
  // ============================================================
  async function shareGameResult() {
    const score = dom.endingScoreVal ? dom.endingScoreVal.textContent : '';
    const title = dom.endingTitleBadge ? dom.endingTitleBadge.textContent : '';
    const text = `[역사야 놀자] ${modeData.title}\n최종 칭호: ${title} (${score})\n당신도 역사적 결단을 내리고 최고 기록에 도전해 보세요!\n👉 https://history.chatgpts.kr/game.html?mode=${currentModeKey}`;

    if (navigator.share) {
      try {
        await navigator.share({
          title: `역사야 놀자 - ${modeData.title}`,
          text: text,
          url: `https://history.chatgpts.kr/game.html?mode=${currentModeKey}`
        });
        return;
      } catch (err) {
        if (err.name !== 'AbortError') copyToClipboard(text);
      }
    } else {
      copyToClipboard(text);
    }
  }

  function copyToClipboard(text) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(() => {
        showToast('📋 게임 결과가 클립보드에 복사되었습니다!');
      }).catch(() => {
        fallbackCopy(text);
      });
    } else {
      fallbackCopy(text);
    }
  }

  function fallbackCopy(text) {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    try {
      document.execCommand('copy');
      showToast('📋 게임 결과가 클립보드에 복사되었습니다!');
    } catch (_) {
      showToast('공유 텍스트 복사에 실패했습니다.');
    }
    document.body.removeChild(ta);
  }

  function escapeHtml(str) {
    return String(str).replace(/[&<>"']/g, c => ({
      '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
    }[c]));
  }

