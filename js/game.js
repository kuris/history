  function switchMode(modeKey) {
    if (!GAME_MODES[modeKey]) modeKey = 'imjin';
    currentModeKey = modeKey;
    modeData = GAME_MODES[modeKey];
    currentStageIndex = 0;
    currentScore = 0;
    isStageComplete = false;

    currentResources = {};
    modeData.resources.forEach(res => {
      currentResources[res.key] = res.initial;
    });

    // 히어로 배너 테마 적용
    if (dom.heroSection) {
      dom.heroSection.className = `game-hero ${modeData.themeClass}`;
    }
    if (dom.heroBadge) dom.heroBadge.innerHTML = modeData.badgeText;
    if (dom.heroTitle) dom.heroTitle.textContent = modeData.title;
    if (dom.heroDesc) dom.heroDesc.textContent = modeData.desc;

    // 모드 칩 활성화 상태 갱신
    if (dom.modeSelector) {
      const btns = dom.modeSelector.querySelectorAll('.mode-chip-btn');
      btns.forEach(btn => {
        if (btn.getAttribute('data-mode') === modeKey) {
          btn.classList.add('active');
          btn.scrollIntoView({ behavior: 'smooth', inline: 'center', block: 'nearest' });
        } else {
          btn.classList.remove('active');
        }
      });
    }

    try {
      const url = new URL(window.location.href);
      url.searchParams.set('mode', modeKey);
      window.history.replaceState({}, '', url);
    } catch (_) {}

    updateBestScoreDisplay();
    buildHUDCards();
    buildMapUI();
    buildSceneDots();
    renderStage(0);
  }

  function updateBestScoreDisplay() {
    if (!dom.bestScoreVal) return;
    const b = getBestScore(currentModeKey);
    dom.bestScoreVal.textContent = b > 0 ? b + '점' : '—';
  }

  function buildHUDCards() {
    if (!dom.statsGrid) return;
    dom.statsGrid.innerHTML = '';

    modeData.resources.forEach(res => {
      const card = document.createElement('div');
      card.className = 'game-stat-card';
      card.id = `stat-card-${res.key}`;
      card.innerHTML = `
        <div class="game-stat-head">
          <span class="game-stat-label">${res.icon} ${res.name}</span>
          <span class="game-stat-value" id="val-${res.key}">${currentResources[res.key]}</span>
        </div>
        <div class="game-stat-bar-bg">
          <div class="game-stat-bar ${res.class}" id="bar-${res.key}" style="width: ${(currentResources[res.key] / res.max) * 100}%;"></div>
        </div>
      `;
      dom.statsGrid.appendChild(card);
    });
  }

  function buildSceneDots() {
    if (!dom.sceneDots) return;
    dom.sceneDots.innerHTML = '';
    modeData.stages.forEach((_, idx) => {
      const dot = document.createElement('div');
      dot.className = `stage-dot ${idx === 0 ? 'current' : ''}`;
      dot.id = `stage-dot-${idx}`;
      dom.sceneDots.appendChild(dot);
    });
  }

  function updateSceneDots(stageIdx) {
    modeData.stages.forEach((_, idx) => {
      const dot = $(`stage-dot-${idx}`);
      if (!dot) return;
      dot.className = 'stage-dot';
      if (idx < stageIdx) dot.classList.add('passed');
      else if (idx === stageIdx) dot.classList.add('current');
    });
  }

