  // 7. 단계 화면 렌더링
  // ============================================================
  function renderStage(stageIdx) {
    const stage = modeData.stages[stageIdx];
    if (!stage) return;

    currentStageIndex = stageIdx;
    isStageComplete = false;

    if (dom.currentStagePill) dom.currentStagePill.textContent = `${stage.step}단계 · ${stage.name || stage.title.split(' ')[0]}`;
    if (dom.stepIndicator) dom.stepIndicator.textContent = `${stage.step} / ${modeData.stages.length}`;

    // 지도 갱신 (토큰 및 패스 이동)
    updateMapPositions(stageIdx);
    updateSceneDots(stageIdx);

    // 상황 액션 카드
    if (dom.sceneTag) dom.sceneTag.textContent = stage.tag;
    if (dom.sceneTitle) dom.sceneTitle.textContent = stage.title;
    if (dom.sceneDesc) dom.sceneDesc.textContent = stage.desc;

    // 결과 배너 및 다음 버튼 숨김 초기화
    if (dom.resultBanner) dom.resultBanner.classList.remove('show');
    if (dom.nextRow) dom.nextRow.classList.remove('show');

    // 역사 돋보기 지식 카드
    if (dom.historyCardTag) dom.historyCardTag.textContent = `역사 탐구 돋보기 · ${stage.name || stage.title.split(' ')[0]}`;
    if (dom.historyCardTitle) dom.historyCardTitle.textContent = stage.historyTitle;
    if (dom.historyCardText) dom.historyCardText.textContent = stage.historyContent;

    // 선택지 렌더링
    renderChoices(stage.choices);
  }

  function renderChoices(choices) {
    if (!dom.choicesList) return;
    dom.choicesList.innerHTML = '';

    choices.forEach((choice, idx) => {
      const btn = document.createElement('button');
      btn.type = 'button';
      btn.className = 'game-choice-btn';
      btn.innerHTML = `
        <span class="choice-num">${idx + 1}</span>
        <span class="choice-text">${escapeHtml(choice.text)}</span>
        <span class="choice-arrow"><i class="fa-solid fa-chevron-right"></i></span>
      `;
      btn.addEventListener('click', () => onChoiceSelected(choice, btn));
      dom.choicesList.appendChild(btn);
    });
  }

  // ============================================================
  // 8. 선택지 클릭 처리
  // ============================================================
  function onChoiceSelected(choice, chosenBtn) {
    if (isStageComplete) return;
    isStageComplete = true;

    const allBtns = dom.choicesList.querySelectorAll('.game-choice-btn');
    allBtns.forEach(b => {
      b.disabled = true;
      b.classList.remove('selected');
    });
    chosenBtn.classList.add('selected');

    modeData.resources.forEach(res => {
      if (choice.effect[res.key]) {
        currentResources[res.key] = Math.max(0, currentResources[res.key] + choice.effect[res.key]);
      }
    });

    if (choice.effect.score) {
      currentScore += choice.effect.score;
    }

    updateHUD(choice.effect);

    if (dom.resultBanner) {
      dom.resultBanner.classList.add('show');
      if (dom.resultText) dom.resultText.textContent = choice.log;

      if (dom.resultDeltas) {
        dom.resultDeltas.innerHTML = '';
        modeData.resources.forEach(res => {
          const delta = choice.effect[res.key];
          if (delta && delta !== 0) {
            const isPos = delta > 0;
            const pill = document.createElement('span');
            pill.className = `delta-pill ${isPos ? 'delta-positive' : 'delta-negative'}`;
            pill.textContent = `${res.icon} ${res.name} ${isPos ? '+' : ''}${delta}`;
            dom.resultDeltas.appendChild(pill);
          }
        });
      }
    }

    const isLast = currentStageIndex >= modeData.stages.length - 1;
    if (dom.nextRow && dom.nextBtn) {
      dom.nextRow.classList.add('show');
      dom.nextBtn.innerHTML = isLast
        ? '<i class="fa-solid fa-trophy"></i> 최종 결전 완료! 결과 보기'
        : '<i class="fa-solid fa-arrow-right"></i> 다음 역사적 국면으로 이동';
    }
  }

  // ============================================================
  // 9. 다음 단계 및 엔딩 처리
  // ============================================================
  function nextStage() {
    if (currentStageIndex < modeData.stages.length - 1) {
      currentStageIndex++;
      renderStage(currentStageIndex);

      if (dom.hudSection) {
        dom.hudSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }
    } else {
      showEnding();
    }
  }

  function showEnding() {
    let resourceBonus = 0;
    modeData.resources.forEach(res => {
      resourceBonus += Math.floor((currentResources[res.key] || 0) / 4);
    });
    const finalScore = currentScore + resourceBonus;

    const prevBest = getBestScore(currentModeKey);
    const isNewBest = saveBestScore(currentModeKey, finalScore);
    updateBestScoreDisplay();

    const { titleBadge, badgeIcon, badgeCode } = calculateBadgeAndTitle(currentModeKey, finalScore);
    saveBadge(badgeCode);

    syncGameRecordWithUser({
      mode: currentModeKey,
      title: modeData.title,
      score: finalScore,
      titleBadge: titleBadge,
      resources: currentResources
    });

    if (dom.endingBadgeIcon) dom.endingBadgeIcon.textContent = badgeIcon;
    if (dom.endingTitle) dom.endingTitle.textContent = '역사적 위업 달성 완료!';
    if (dom.endingSubtitle) {
      dom.endingSubtitle.innerHTML = `역사의 중대한 기로에서 용기 있는 결단으로 역사를 훌륭히 이끌었습니다.`;
    }
    if (dom.endingScoreVal) dom.endingScoreVal.textContent = finalScore + '점';
    if (dom.endingTitleBadge) dom.endingTitleBadge.textContent = titleBadge;

    if (dom.endingStatsSummary) {
      dom.endingStatsSummary.innerHTML = '';
      modeData.resources.forEach(res => {
        const box = document.createElement('div');
        box.className = 'summary-stat-box';
        box.innerHTML = `
          <span>${res.icon} ${res.name}</span>
          <strong>${currentResources[res.key]}</strong>
        `;
        dom.endingStatsSummary.appendChild(box);
      });
    }

    if (dom.endingBestNotice) {
      dom.endingBestNotice.innerHTML = isNewBest
        ? '<span style="color:#059669;font-weight:900;">🎉 축하합니다! 새로운 최고 기록을 달성했습니다!</span>'
        : `이전 최고 점수: <strong>${prevBest}점</strong>`;
    }

    if (dom.endingTakeawaysList) {
      dom.endingTakeawaysList.innerHTML = '';
      const takeaways = getTakeaways(currentModeKey);
      takeaways.forEach(t => {
        const li = document.createElement('li');
        li.innerHTML = t;
        dom.endingTakeawaysList.appendChild(li);
      });
    }

    if (dom.endingRelatedLinks) {
      dom.endingRelatedLinks.innerHTML = '';
      modeData.relatedLinks.forEach(link => {
        const a = document.createElement('a');
        a.href = link.url;
        a.className = 'ending-btn-sub';
        a.innerHTML = link.text;
        dom.endingRelatedLinks.appendChild(a);
      });
    }

    if (dom.endingOverlay) {
      dom.endingOverlay.classList.add('show');
    }
  }

