  // ============================================================
  function getBestScore(modeKey) {
    try {
      const v = localStorage.getItem(`history_game_best_${modeKey}`);
      return v ? parseInt(v, 10) : 0;
    } catch (_) {
      return 0;
    }
  }

  function saveBestScore(modeKey, score) {
    try {
      const current = getBestScore(modeKey);
      if (score > current) {
        localStorage.setItem(`history_game_best_${modeKey}`, String(score));
        return true;
      }
    } catch (_) {}
    return false;
  }

  function saveBadge(badgeName) {
    try {
      const stored = JSON.parse(localStorage.getItem('history_game_badges') || '[]');
      if (!stored.includes(badgeName)) {
        stored.push(badgeName);
        localStorage.setItem('history_game_badges', JSON.stringify(stored));
      }
    } catch (_) {}
  }

  async function syncGameRecordWithUser(recordData) {
    if (typeof window !== 'undefined' && window.CGAuth && window.CGAuth.isLoggedIn && window.CGAuth.isLoggedIn()) {
      try {
        window.CGAuth.touchRecent({
          kind: 'game',
          id: recordData.mode,
          title: recordData.title,
          url: `game.html?mode=${recordData.mode}`
        });

        if (typeof window.CGAuth.upsertRecord === 'function') {
          await window.CGAuth.upsertRecord('game_records', {
            game_mode: recordData.mode,
            score: recordData.score,
            title_badge: recordData.titleBadge,
            resources: recordData.resources,
            completed_at: new Date().toISOString()
          });
        }
      } catch (e) {
        console.warn('[Game] Supabase sync skipped:', e);
      }
    }
  }

